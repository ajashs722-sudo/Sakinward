/**
 * Returns the exact verified audio URL for an Ayah purely from official AlQuran Cloud CDN
 */
export function getAyahAudioUrl(
  reciterId: string,
  ayahGlobalNumber: number,
  _surahNumber?: number,
  _ayahInSurah?: number
): string {
  // Find reciter bitrate
  const reciter = QURAN_RECITERS.find((r) => r.id === reciterId);
  const bitrate = reciter?.bitrate || 128;
  const verifiedReciterId = reciter?.id || 'ar.alafasy';

  return `https://cdn.islamic.network/quran/audio/${bitrate}/${verifiedReciterId}/${ayahGlobalNumber}.mp3`;
}

